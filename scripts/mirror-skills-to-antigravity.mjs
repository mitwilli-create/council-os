#!/usr/bin/env node
/**
 * mirror-skills-to-antigravity.mjs — mirror Council OS skills to Google Antigravity's
 * YAML skill directory format.
 *
 * Antigravity uses YAML-format skill files in:
 *   - Global:    ~/.gemini/antigravity/skills/
 *   - Workspace: <workspace-root>/.agents/skills/
 *
 * This script converts Mitchell's ~/.claude/skills/*.md (Anthropic-format with
 * YAML frontmatter + markdown body) into ~/.gemini/antigravity/skills/*.yaml
 * (Antigravity-format with body as a YAML string field).
 *
 * Behavior:
 *   - If ~/.gemini/antigravity/skills/ does NOT exist, exit cleanly with a note
 *     (Antigravity not installed yet — script is safe to re-run after install).
 *   - If it DOES exist, copy each ~/.claude/skills/*.md to *.yaml, mapping:
 *       - YAML frontmatter → top-level YAML fields
 *       - Markdown body → `body:` field as a literal block scalar
 *   - Idempotent: re-running overwrites mirrored files (safe to re-run after edits).
 *
 * Skills mirrored (the council-related ones; user-specific skills like
 * make-it-sound-like-mitchell stay Anthropic-only):
 *   - sonar-structured-research.md
 *   - openai-terminal-agent.md
 *   - council.md (if exists)
 *   - researcher.md (if exists)
 *   - dealbreaker.md (if exists)
 *
 * Usage:
 *   node ~/Documents/council-os/scripts/mirror-skills-to-antigravity.mjs
 *
 * Generated by dealbreaker-v2 + meta-audit P2 (2026-05-18).
 */

import {
  existsSync, mkdirSync, readFileSync, writeFileSync,
  readdirSync, statSync,
} from 'node:fs';
import { homedir } from 'node:os';
import { join } from 'node:path';

const HOME = homedir();
const CLAUDE_SKILLS = `${HOME}/.claude/skills`;
const ANTIGRAVITY_SKILLS = `${HOME}/.gemini/antigravity/skills`;

// Skills that are council/research-related and worth mirroring.
// Excludes Mitchell-personal skills (make-it-sound-like-mitchell, habit-architect, etc.)
const MIRROR_LIST = [
  'sonar-structured-research.md',
  'openai-terminal-agent.md',
];

// Also mirror the council-related agent files (they're used like skills in some
// invocation patterns). Mirror from ~/.claude/agents/ → as `agent-X.yaml` to
// distinguish from skill files.
const CLAUDE_AGENTS = `${HOME}/.claude/agents`;
const AGENT_MIRROR_LIST = [
  'researcher.md',
  'dealbreaker.md',
  'council-of-models.md',
];

function parseMarkdownWithFrontmatter(content) {
  const fmMatch = content.match(/^---\n([\s\S]*?)\n---\n([\s\S]*)$/);
  if (!fmMatch) return { frontmatter: {}, body: content.trim() };
  const fmLines = fmMatch[1].split('\n');
  const frontmatter = {};
  let lastKey = null;
  for (const line of fmLines) {
    const kvMatch = line.match(/^(\w[\w_]*):\s*(.*)$/);
    if (kvMatch) {
      const [, key, value] = kvMatch;
      frontmatter[key] = value.trim();
      lastKey = key;
    } else if (line.trim().startsWith('-') && lastKey) {
      if (!Array.isArray(frontmatter[lastKey])) frontmatter[lastKey] = [];
      frontmatter[lastKey].push(line.trim().slice(1).trim());
    }
  }
  return { frontmatter, body: fmMatch[2].trim() };
}

function escapeYamlValue(v) {
  if (typeof v !== 'string') return JSON.stringify(v);
  // If value contains special chars, quote it; otherwise leave bare
  if (/[:#{}[\],&*?|<>=!%@`'"]|^\s|\s$/.test(v)) {
    return JSON.stringify(v);
  }
  return v;
}

function toAntigravityYaml(name, { frontmatter, body }, kind = 'skill') {
  // Antigravity skill schema (inferred from Google docs; subject to evolution):
  //   name: string
  //   kind: skill | agent
  //   description: string
  //   model_target: string (optional)
  //   verified: ISO date (optional)
  //   primary_sources: list (optional)
  //   body: |
  //     literal block scalar (the full markdown body)
  const fields = [];
  fields.push(`name: ${escapeYamlValue(frontmatter.name || name)}`);
  fields.push(`kind: ${kind}`);
  if (frontmatter.description) fields.push(`description: ${escapeYamlValue(frontmatter.description)}`);
  if (frontmatter.model_target) fields.push(`model_target: ${escapeYamlValue(frontmatter.model_target)}`);
  if (frontmatter.verified) fields.push(`verified: ${escapeYamlValue(frontmatter.verified)}`);
  if (frontmatter.tools) fields.push(`tools: ${escapeYamlValue(frontmatter.tools)}`);
  if (frontmatter.benchmark) fields.push(`benchmark: ${escapeYamlValue(frontmatter.benchmark)}`);
  if (frontmatter.wiring_status) fields.push(`wiring_status: ${escapeYamlValue(frontmatter.wiring_status)}`);
  if (frontmatter.primary_sources && Array.isArray(frontmatter.primary_sources)) {
    fields.push('primary_sources:');
    for (const src of frontmatter.primary_sources) {
      fields.push(`  - ${escapeYamlValue(src)}`);
    }
  }
  fields.push('mirrored_from: ~/.claude/' + (kind === 'agent' ? 'agents' : 'skills') + '/' + name);
  fields.push('mirrored_at: ' + new Date().toISOString());
  fields.push('');
  fields.push('body: |');
  // Indent the body by 2 spaces for the literal block scalar
  const indentedBody = body.split('\n').map(l => '  ' + l).join('\n');
  fields.push(indentedBody);
  return fields.join('\n') + '\n';
}

function mirror(sourceFile, destDir, sourceDir, kind) {
  const sourcePath = `${sourceDir}/${sourceFile}`;
  if (!existsSync(sourcePath)) {
    console.log(`[skip] ${sourceFile} not found at ${sourceDir}`);
    return false;
  }
  const content = readFileSync(sourcePath, 'utf-8');
  const parsed = parseMarkdownWithFrontmatter(content);
  const yaml = toAntigravityYaml(sourceFile, parsed, kind);
  const destFile = `${destDir}/${sourceFile.replace(/\.md$/, '.yaml')}`;
  writeFileSync(destFile, yaml, 'utf-8');
  console.log(`[mirror] ${sourceFile} → ${destFile} (${yaml.length} chars)`);
  return true;
}

// ─────────────────────────────────────────────────────────────────────────
// Main
// ─────────────────────────────────────────────────────────────────────────

const antigravityHome = `${HOME}/.gemini/antigravity`;
if (!existsSync(antigravityHome)) {
  console.log(`Antigravity not installed (${antigravityHome} does not exist).`);
  console.log(`Skipping mirror — re-run this script after Antigravity install:`);
  console.log(`  node ~/Documents/council-os/scripts/mirror-skills-to-antigravity.mjs`);
  console.log(`\nWhen run after install, will mirror:`);
  for (const s of MIRROR_LIST) console.log(`  - ~/.claude/skills/${s} → ~/.gemini/antigravity/skills/${s.replace(/\.md$/, '.yaml')}`);
  for (const s of AGENT_MIRROR_LIST) console.log(`  - ~/.claude/agents/${s} → ~/.gemini/antigravity/skills/${s.replace(/\.md$/, '.yaml')}`);
  process.exit(0);
}

// Ensure target dir exists
if (!existsSync(ANTIGRAVITY_SKILLS)) {
  mkdirSync(ANTIGRAVITY_SKILLS, { recursive: true });
  console.log(`Created ${ANTIGRAVITY_SKILLS}`);
}

console.log(`Mirroring skills → ${ANTIGRAVITY_SKILLS}\n`);

let mirrored = 0;
for (const s of MIRROR_LIST) {
  if (mirror(s, ANTIGRAVITY_SKILLS, CLAUDE_SKILLS, 'skill')) mirrored++;
}
for (const s of AGENT_MIRROR_LIST) {
  if (mirror(s, ANTIGRAVITY_SKILLS, CLAUDE_AGENTS, 'agent')) mirrored++;
}

console.log(`\n${mirrored}/${MIRROR_LIST.length + AGENT_MIRROR_LIST.length} skills/agents mirrored.`);
console.log(`Re-run after editing source files to keep Antigravity copies in sync.`);
